export function tradutor(lang) {
  const d = UI[lang] || UI.pt;
  return (k, vars) => {
    const v = d[k] ?? UI.pt[k];
    if (v === undefined) throw new Error(`Texto sem tradução: ${k}`);
    return vars && typeof v === 'string' ? v.replace(/\{(\w+)\}/g, (_, n) => vars[n] ?? '') : v;
  };
}

